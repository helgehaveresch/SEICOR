"""Run plume_preprocessor.py for a fixed set of 20 test days into separate test output folders.

The settings are those of plume_preprocessor_settings.yaml, except that every Output folder gets the
suffix "_test" (analysis_test, plumes_test, ship_passes_test, video_test, IMPACT_coarsened_test), so a
test run never touches the output of the campaign run. The test settings are written to
plume_preprocessor_settings_test.yaml (generated, do not edit) and passed to the preprocessor via the
environment variable PLUME_SETTINGS_PATH.

Usage (from any directory):
    python3 run_plume_preprocessor_test.py                 # all 20 test days
    python3 run_plume_preprocessor_test.py 250520 260217   # only these days
In the background, detached from the terminal:
    setsid nohup python3 run_plume_preprocessor_test.py > plume_preprocessor_test_run_$(date +%y%m%d_%H%M).log 2>&1 &
"""
import multiprocessing
import os
import shutil
import subprocess
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
SETTINGS = HERE / "plume_preprocessor_settings.yaml"
TEST_SETTINGS = HERE / "plume_preprocessor_settings_test.yaml"
SUFFIX = "_test"

# 20 test days spread over the whole campaign (250326-260611), at least one per month with SD data, mostly
# days of the processing-steps shortlist; all ran successfully in the campaign run of 261114
TEST_DATES = [
    "250328", "250405", "250416", "250511", "250520", "250531",  # Mar-May 2025
    "250622", "250707", "250813", "250830", "250923",            # Jun-Sep 2025
    "251006", "251219", "260120", "260217",                      # Oct 2025-Feb 2026
    "260309", "260402", "260418", "260529", "260602",            # Mar-Jun 2026
]

CLEAN_PLUME_FOLDERS = True  # delete plumes_test/plumes_<date> before a day runs, so no plume files of older test runs remain
PROCESSES = 20


def write_test_settings():
    """Copy of the settings with the suffix SUFFIX on every Output folder; returns the settings."""
    settings = yaml.safe_load(SETTINGS.read_text())
    settings["Output"] = {key: value + SUFFIX for key, value in settings["Output"].items()}
    header = (f"# GENERATED by {Path(__file__).name} from {SETTINGS.name}: same settings, Output folders with suffix "
              f"'{SUFFIX}'.\n# Do not edit, edit {SETTINGS.name} instead.\n")
    TEST_SETTINGS.write_text(header + yaml.safe_dump(settings, sort_keys=False, allow_unicode=True))
    return settings


def run_for_date(date):
    print(f"[PID {os.getpid()}] Running plume_preprocessor (test settings) for date: {date}", flush=True)
    env = {**os.environ, "PLUME_SETTINGS_PATH": str(TEST_SETTINGS), "MPLBACKEND": "Agg"}
    try:
        cp = subprocess.run([sys.executable, str(HERE / "plume_preprocessor.py"), date], env=env,
                            stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
        print(cp.stdout or f"Finished plume_preprocessor for date: {date} (rc={cp.returncode})", flush=True)
        if cp.returncode == 0 and "SKIPPED:" in (cp.stdout or ""):
            return date, "skipped"
        return date, cp.returncode
    except Exception as e:
        print(f"Error running date {date}: {e}", flush=True)
        return date, 1


if __name__ == "__main__":
    dates = sys.argv[1:] or TEST_DATES
    settings = write_test_settings()
    print(f"test settings: {TEST_SETTINGS}\noutput folders: {settings['Output']}\ndates ({len(dates)}): {dates}", flush=True)

    if CLEAN_PLUME_FOLDERS:
        plume_dir = Path(settings["base_paths"]["linux" if sys.platform.startswith("linux") else "windows"]) / settings["Output"]["plume_out_dir"]
        assert plume_dir.name.endswith(SUFFIX), plume_dir  # never clean the campaign output
        for date in dates:
            shutil.rmtree(plume_dir / f"plumes_{date}", ignore_errors=True)

    with multiprocessing.Pool(processes=min(PROCESSES, len(dates))) as pool:
        results = pool.map(run_for_date, dates)

    skipped = [d for d, rc in results if rc == "skipped"]
    if skipped:
        print(f"Skipped {len(skipped)} dates without SD measurements:", skipped)
    failed = [d for d, rc in results if rc not in (0, "skipped")]
    if failed:
        print("The following dates failed:", failed)
        raise SystemExit(1)
    print("All test dates processed successfully.")
